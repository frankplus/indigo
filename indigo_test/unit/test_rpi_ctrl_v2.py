	# --set-wifi-server: only the AP profile changes

	def test_set_wifi_server_keeps_client_profiles(self):
		sandbox = self.sandbox([client_profile(HOME_PROFILE, "Home", "home-password")], HOME_PROFILE)
		self.assert_result(sandbox.run("--set-wifi-server", "astro", "astro-password"), "OK\n", 0)
		self.assertEqual(sandbox.profiles(), sorted([HOME_PROFILE, "indigo-ap"]))
		self.assertEqual(sandbox.active(), "indigo-ap")
		self.assertFalse([call for call in sandbox.calls("nmcli") if "delete" in call])
		modify = [call for call in sandbox.mutations() if call[2] == "modify"]
		self.assertEqual(len(modify), 1, modify)
		self.assertIn("connection.autoconnect", modify[0])
		self.assertEqual(modify[0][modify[0].index("connection.autoconnect") + 1], "no")
		self.assertEqual(modify[0][modify[0].index("802-11-wireless-security.psk") + 1], "astro-password")

