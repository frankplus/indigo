	# --set-wifi-client: validates, replies at once, switches detached

	def test_set_wifi_client_rejects_invalid_password_length(self):
		for length, message in ((1, "WIFI_CN_PW length < 8"), (7, "WIFI_CN_PW length < 8"), (64, "WIFI_CN_PW length > 63")):
			with self.subTest(length=length):
				sandbox = self.sandbox(pcre=False)
				self.assert_result(sandbox.run("--set-wifi-client", SSID, "p" * length), "ALERT: " + message + "\n", 1)
				self.assertEqual(sandbox.calls(), [], "commands issued after an invalid password")

	def test_set_wifi_client_replies_and_switches_detached(self):
		for password in (PASSWORD, "p" * 8, "p" * 63, ""):
			with self.subTest(length=len(password)):
				sandbox = self.sandbox([ap_profile()], "indigo-ap", pcre=False)
				self.assert_result(sandbox.run("--set-wifi-client", SSID, password), "OK\n", 0)
				password_file = sandbox.run_dir / "client-psk"
				self.assertEqual(password_file.read_text(), password)
				self.assertEqual(stat.S_IMODE(password_file.stat().st_mode), 0o600)
				self.assertEqual(sandbox.calls("systemd-run"), [["systemd-run", "--quiet", "--collect", "--unit=indigo-wifi-switch", "--", str(sandbox.script), "--switch-wifi-client", SSID, str(password_file)]])
				# The network is not touched before the reply.
				self.assertEqual(sandbox.mutations(), [])
				self.assertEqual(sandbox.active(), "indigo-ap")

