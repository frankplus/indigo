"""Check tools/rpi_ctrl_v2.sh without hardware: WiFi settings readback of any
active profile, the separate AP profile, the detached client switch and its
fallback, the AP fallback (--reset-wifi-server), version install and argument
parsing.

The script is copied into a temporary directory with its system file paths
redirected there and run with a PATH that holds only stubs and symlinks to a
few harmless real tools (grep, head, tr, which). Every stub logs its argv.
nmcli is a small fake NetworkManager whose profiles, active connection and
device state are files in the sandbox. No network, service, package or power
command of the host is reachable: anything not stubbed or allowlisted fails as
"command not found".
"""

