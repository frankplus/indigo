	# --switch-wifi-client: the detached part

	def switch(self, sandbox, password=PASSWORD, ssid=SSID):
		password_file = sandbox.run_dir / "client-psk"
		password_file.write_text(password)
		result = sandbox.run("--switch-wifi-client", ssid, str(password_file))
		self.assertIn(["rm", "-f", str(password_file)], sandbox.calls("rm"))
		return result

	def test_switch_from_ap_to_new_network(self):
		sandbox = self.sandbox([ap_profile()], "indigo-ap")
		self.assert_result(self.switch(sandbox), "OK\n", 0)
		con = "indigo-" + SSID
		self.assertEqual(sandbox.active(), con)
		self.assertEqual(sandbox.profiles(), sorted(["indigo-ap", con]))
		calls = sandbox.calls("nmcli")
		self.assertIn(["nmcli", "con", "add", "type", "wifi", "ifname", "wlan0", "con-name", con, "ssid", SSID], calls)
		self.assertIn(["nmcli", "con", "modify", con, "802-11-wireless-security.key-mgmt", "wpa-psk", "802-11-wireless-security.psk", PASSWORD], calls)
		self.assertIn(["nmcli", "con", "modify", con, "connection.autoconnect", "yes", "connection.autoconnect-priority", "10"], calls)
		# The AP goes down before the scan; a single radio cannot scan as an AP.
		down = calls.index(["nmcli", "con", "down", "indigo-ap"])
		scan = calls.index(["nmcli", "-w", "15", "dev", "wifi", "list", "--rescan", "yes"])
		up = calls.index(["nmcli", "-w", "60", "con", "up", con])
		self.assertLess(down, scan)
		self.assertLess(scan, up)

